def lookup_box_metadata(name: str) -> BoxMetadata:
    """Resolve curated series/MSRP/release metadata for a normalized or raw box name."""
    key = normalize_product_name(name)
    if key in BOX_CATALOG:
        return BOX_CATALOG[key]
    raw_key = str(name or "").strip().casefold()
    if raw_key in BOX_CATALOG:
        return BOX_CATALOG[raw_key]

    inferred_series = "旧裏・その他"
    if "スペシャル" in key or "ポケセン" in key or "golden" in key or "futuristic" in key:
        inferred_series = "スペシャルBOX"
    elif "30th" in key:
        inferred_series = "MEGA"
    elif any(marker in key for marker in ("xy", "bw", "cp")):
        inferred_series = "XY・BW"

    return BoxMetadata(
        canonical_name=key or raw_key,
        display_name=str(name or "").strip() or key,
        series=inferred_series,
        set_code="",
        msrp_yen=None,
        release_date="",
    )


def box_series_label(name: str) -> str:
    return lookup_box_metadata(name).series


def box_msrp_yen(name: str) -> int | None:
    return lookup_box_metadata(name).msrp_yen
